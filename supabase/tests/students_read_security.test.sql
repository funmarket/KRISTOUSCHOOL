begin;
set local search_path = public, extensions;
select plan(16);
select has_function('public','list_school_students',array['text','uuid','uuid','text','integer','integer']);
select has_function('public','get_school_student_identity',array['uuid']);
select function_returns('public','list_school_students',array['text','uuid','uuid','text','integer','integer'],'jsonb');
select function_returns('public','get_school_student_identity',array['uuid'],'jsonb');
select ok(not has_function_privilege('anon','public.list_school_students(text,uuid,uuid,text,integer,integer)','EXECUTE'),'anonymous search execute denied');
select ok(not has_function_privilege('anon','public.get_school_student_identity(uuid)','EXECUTE'),'anonymous detail execute denied');
select ok(has_function_privilege('authenticated','public.list_school_students(text,uuid,uuid,text,integer,integer)','EXECUTE'),'authenticated search transport available; function enforces policy');
select ok(has_function_privilege('authenticated','public.get_school_student_identity(uuid)','EXECUTE'),'authenticated detail transport available; function enforces policy');
select ok((select relrowsecurity from pg_class where oid='public.students'::regclass),'existing pupil RLS stays enabled');
select ok((select relrowsecurity from pg_class where oid='public.student_class_memberships'::regclass),'existing membership RLS stays enabled');
select is((select provolatile::text from pg_proc where oid='public.list_school_students(text,uuid,uuid,text,integer,integer)'::regprocedure),'s','search uses a consistent statement snapshot');
select is((select provolatile::text from pg_proc where oid='public.get_school_student_identity(uuid)'::regprocedure),'s','detail uses a consistent statement snapshot');
select set_config('request.jwt.claim.sub','',true);
select throws_ok('select public.list_school_students()','P0001','actor_unauthenticated','missing verified actor cannot search');
select throws_ok('select public.get_school_student_identity(null)','P0001','actor_unauthenticated','authorization precedes pupil lookup');
set local role anon;
select throws_ok('select public.list_school_students()','42501','permission denied for function list_school_students','anonymous direct API denied');
select throws_ok('select public.get_school_student_identity(null)','42501','permission denied for function get_school_student_identity','anonymous direct detail denied');
reset role;
select * from finish();
rollback;
